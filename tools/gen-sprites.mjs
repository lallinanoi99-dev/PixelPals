// Packs the art from assets/sprites.js into contracts/PixelPals.sol (between the // <art> markers)
// and exports every species × stage as an SVG file into assets/sprites/ for the website.
// Usage (from the project root): node tools/gen-sprites.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as S from '../assets/sprites.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CODE = { '.': 0, o: 1, b: 2, a: 3 };

// 12 sprites × (64 bytes of 2-bit pixels + eyeY + headY), index = species * 4 + stage
let hex = '';
for (let sp = 0; sp < 3; sp++) {
  for (let st = 0; st < 4; st++) {
    const g = S.grid(sp, st);
    for (let y = 0; y < 16; y++) {
      for (let x = 0; x < 16; x += 4) {
        let byte = 0;
        for (let k = 0; k < 4; k++) byte = (byte << 2) | CODE[g[y][x + k]];
        hex += byte.toString(16).padStart(2, '0');
      }
    }
    const { eyeY, headY } = S.SPRITES[sp][st];
    hex += eyeY.toString(16).padStart(2, '0') + headY.toString(16).padStart(2, '0');
  }
}

const palettes = S.PALETTES.map((p) => p.slice(1).join('')).join('');

// Overlays (faces, glasses, bow, hat, flower, cloud) as 4 bytes per rect: x, y + 16, width, colour.
// Colour = index into OVERLAY_COLORS; +0x80 marks the semi-transparent blush. Parsed from the
// same SVG snippets renderSVG() uses, so the contract can't drift from the website.
const overlays = [S.FACES[0], S.FACES[1], S.FACES[2], S.GLASSES, S.HEADWEAR[1], S.HEADWEAR[2], S.HEADWEAR[4], S.CLOUD];
const colors = [];
let ovl = '';
const index = [0];
let rects = 0;
for (const snippet of overlays) {
  for (const m of snippet.matchAll(/<rect x="(-?\d+)" y="(-?\d+)" width="(\d+)" height="1" fill="#([0-9A-F]{6})"( opacity="\.7")?\/>/g)) {
    const [, x, y, w, c, blush] = m;
    if (!colors.includes(c)) colors.push(c);
    const bytes = [Number(x), Number(y) + 16, Number(w), colors.indexOf(c) + (blush ? 0x80 : 0)];
    if (bytes.some((v) => v < 0 || v > 255)) throw new Error('overlay value out of range');
    ovl += bytes.map((v) => v.toString(16).padStart(2, '0')).join('');
    rects++;
  }
  index.push(rects);
}
const check = overlays.map((o) => (o.match(/<rect/g) || []).length).reduce((a, b) => a + b, 0);
if (check !== rects) throw new Error(`parsed ${rects} of ${check} overlay rects — format changed?`);

const block = `// <art> generated by tools/gen-sprites.mjs from assets/sprites.js — do not edit by hand
    bytes private constant SPRITES = hex"${hex}";
    bytes private constant PALETTE_HEX = "${palettes}";
    bytes private constant OVERLAYS = hex"${ovl}";
    bytes private constant OVERLAY_INDEX = hex"${index.map((v) => v.toString(16).padStart(2, '0')).join('')}";
    bytes private constant OVERLAY_COLORS = "${colors.join('')}";
    // </art>`;

const solPath = join(root, 'contracts/PixelPals.sol');
const sol = readFileSync(solPath, 'utf8');
const start = sol.indexOf('// <art>');
const end = sol.indexOf('// </art>') + '// </art>'.length;
if (start < 0 || end < start) throw new Error('art markers not found in PixelPals.sol');
writeFileSync(solPath, sol.slice(0, start) + block.trimStart() + sol.slice(end));

// website sprite files: the default look of each species/stage (Strawberry Milk, plain, happy)
mkdirSync(join(root, 'assets/sprites'), { recursive: true });
for (let sp = 0; sp < 3; sp++) {
  for (let st = 0; st < 4; st++) {
    const file = `${S.SPECIES[sp].toLowerCase()}-${S.STAGES[st].toLowerCase()}.svg`;
    writeFileSync(join(root, 'assets/sprites', file), S.renderSVG({ species: sp, stage: st }) + '\n');
  }
}
console.log(`art: ${hex.length / 2} sprite bytes packed; 12 SVGs written to assets/sprites/`);
